-- Motivo obligatorio al descartar (semántica que 3FN no cubre).
CREATE OR REPLACE FUNCTION fn_solicitud_motivo_descarte()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.estado = 'descartada'
       AND (NEW.motivo_descarte IS NULL OR btrim(NEW.motivo_descarte) = '') THEN
        RAISE EXCEPTION
            'La solicitud % está descartada: motivo_descarte es obligatorio',
            COALESCE(NEW.solicitud_id::text, 'nueva');
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_solicitud_motivo_descarte
    BEFORE INSERT OR UPDATE ON solicitudes_propiedad
    FOR EACH ROW
    EXECUTE FUNCTION fn_solicitud_motivo_descarte();

-- R2/R6: el dueño no es el prospecto de la misma propiedad.
CREATE OR REPLACE FUNCTION fn_solicitud_no_es_dueno()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM propiedad_propietarios pp
        WHERE pp.persona_id = NEW.persona_id
          AND pp.propiedad_id = NEW.propiedad_id
    ) THEN
        RAISE EXCEPTION
            'R2/R6: persona_id=% es propietario de propiedad_id=%; no puede ser prospecto de la misma',
            NEW.persona_id, NEW.propiedad_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_solicitud_no_es_dueno
    BEFORE INSERT OR UPDATE OF persona_id, propiedad_id ON solicitudes_propiedad
    FOR EACH ROW
    EXECUTE FUNCTION fn_solicitud_no_es_dueno();

-- La misma regla al revés: no agregar dueño si esa persona ya es prospecto.
CREATE OR REPLACE FUNCTION fn_dueno_no_es_prospecto()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM solicitudes_propiedad s
        WHERE s.persona_id = NEW.persona_id
          AND s.propiedad_id = NEW.propiedad_id
    ) THEN
        RAISE EXCEPTION
            'R2/R6: persona_id=% ya es prospecto de propiedad_id=%; no puede registrarse como dueño',
            NEW.persona_id, NEW.propiedad_id;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_dueno_no_es_prospecto
    BEFORE INSERT OR UPDATE OF persona_id, propiedad_id ON propiedad_propietarios
    FOR EACH ROW
    EXECUTE FUNCTION fn_dueno_no_es_prospecto();

-- R11: oferta aceptada pasa la propiedad de disponible a en_negociacion.
-- Si deja de estar aceptada y nadie más tiene oferta aceptada, vuelve a disponible.
CREATE OR REPLACE FUNCTION fn_oferta_aceptada_en_negociacion()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_propiedad_id integer;
BEGIN
    SELECT s.propiedad_id
      INTO v_propiedad_id
      FROM solicitudes_propiedad s
     WHERE s.solicitud_id = NEW.solicitud_id;

    IF NEW.estado_oferta = 'aceptada'
       AND (TG_OP = 'INSERT' OR OLD.estado_oferta IS DISTINCT FROM 'aceptada') THEN
        UPDATE propiedades
           SET estado_comercial = 'en_negociacion'
         WHERE propiedad_id = v_propiedad_id
           AND estado_comercial = 'disponible';

        UPDATE solicitudes_propiedad
           SET estado = 'en_negociacion'
         WHERE solicitud_id = NEW.solicitud_id
           AND estado IN ('nueva', 'en_seguimiento');
    ELSIF TG_OP = 'UPDATE'
          AND OLD.estado_oferta = 'aceptada'
          AND NEW.estado_oferta IS DISTINCT FROM 'aceptada' THEN
        UPDATE solicitudes_propiedad
           SET estado = 'en_seguimiento'
         WHERE solicitud_id = NEW.solicitud_id
           AND estado = 'en_negociacion';

        IF NOT EXISTS (
            SELECT 1
            FROM ofertas o
            JOIN solicitudes_propiedad s ON s.solicitud_id = o.solicitud_id
            WHERE s.propiedad_id = v_propiedad_id
              AND o.estado_oferta = 'aceptada'
              AND o.oferta_id <> NEW.oferta_id
        ) THEN
            UPDATE propiedades
               SET estado_comercial = 'disponible'
             WHERE propiedad_id = v_propiedad_id
               AND estado_comercial = 'en_negociacion';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_oferta_aceptada_en_negociacion
    AFTER INSERT OR UPDATE OF estado_oferta ON ofertas
    FOR EACH ROW
    EXECUTE FUNCTION fn_oferta_aceptada_en_negociacion();

-- R12/R16: una transacción anulada no cambia el inmueble.
-- Solo se cierra una oferta aceptada, y solo si la propiedad no tiene otro cierre.
-- El aviso vigente más reciente define vendida o no_disponible.
CREATE OR REPLACE FUNCTION fn_validar_y_aplicar_transaccion()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado_oferta text;
    v_solicitud_id  integer;
    v_propiedad_id  integer;
    v_tipo          text;
BEGIN
    SELECT o.estado_oferta, o.solicitud_id, s.propiedad_id
      INTO v_estado_oferta, v_solicitud_id, v_propiedad_id
      FROM ofertas o
      JOIN solicitudes_propiedad s ON s.solicitud_id = o.solicitud_id
     WHERE o.oferta_id = NEW.oferta_id;

    IF NEW.estado = 'anulada' THEN
        RETURN NEW;
    END IF;

    IF v_estado_oferta IS DISTINCT FROM 'aceptada' THEN
        RAISE EXCEPTION
            'R12: la transacción exige oferta aceptada (oferta_id=%, estado=%)',
            NEW.oferta_id, v_estado_oferta;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM transacciones t
        JOIN ofertas o ON o.oferta_id = t.oferta_id
        JOIN solicitudes_propiedad s ON s.solicitud_id = o.solicitud_id
        WHERE s.propiedad_id = v_propiedad_id
          AND t.estado <> 'anulada'
          AND t.oferta_id <> NEW.oferta_id
    ) OR EXISTS (
        SELECT 1
        FROM propiedades p
        WHERE p.propiedad_id = v_propiedad_id
          AND p.estado_comercial = 'vendida'
    ) THEN
        RAISE EXCEPTION
            'R12: la propiedad % ya tiene un cierre vigente',
            v_propiedad_id;
    END IF;

    UPDATE solicitudes_propiedad
       SET estado = 'ganada',
           fecha_cierre = COALESCE(fecha_cierre, now())
     WHERE solicitud_id = v_solicitud_id;

    -- El aviso vigente más reciente define venta o arriendo. No se privilegia la venta.
    SELECT t.nombre
      INTO v_tipo
      FROM publicaciones pub
      JOIN tipos_operacion t ON t.tipo_operacion_id = pub.tipo_operacion_id
     WHERE pub.propiedad_id = v_propiedad_id
     ORDER BY pub.publicada DESC, pub.fecha_publicacion DESC
     LIMIT 1;

    IF v_tipo = 'venta' THEN
        UPDATE propiedades
           SET estado_comercial = 'vendida'
         WHERE propiedad_id = v_propiedad_id;
    ELSE
        UPDATE propiedades
           SET estado_comercial = 'no_disponible'
         WHERE propiedad_id = v_propiedad_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validar_y_aplicar_transaccion
    BEFORE INSERT ON transacciones
    FOR EACH ROW
    EXECUTE FUNCTION fn_validar_y_aplicar_transaccion();

-- Función de dominio para registrar un cierre en una sola llamada (R12).
CREATE OR REPLACE FUNCTION registrar_cierre(
    p_oferta_id           integer,
    p_empleado_id         integer,
    p_valor_final         numeric,
    p_comision_porcentaje numeric,
    p_fecha_inicio        date,
    p_fecha_fin           date DEFAULT NULL,
    p_estado              varchar DEFAULT 'cerrada'
)
RETURNS integer
LANGUAGE plpgsql
AS $$
DECLARE
    v_id integer;
BEGIN
    INSERT INTO transacciones (
        oferta_id, empleado_id, valor_final, comision_porcentaje,
        fecha_inicio_contrato, fecha_fin_contrato, estado
    ) VALUES (
        p_oferta_id, p_empleado_id, p_valor_final, p_comision_porcentaje,
        p_fecha_inicio, p_fecha_fin, p_estado
    )
    RETURNING transaccion_id INTO v_id;

    RETURN v_id;
END;
$$;

